"""Subcommand: scaffold a new benchmark from the `minimal` template.

Usage::

    arvis add-benchmark <name>

Creates ``targets/benchmarks/<name>/`` populated with the minimum files the
ARVIS pipeline expects:

* ``main.c`` — stub entry point you fill in with your workload.
* ``crt0.S`` and ``link.ld`` — bare-metal startup and linker script for the
  CV32E40P / Verilator target.
* ``crt0_spike.S`` and ``link_spike.ld`` — startup and linker script for the
  Spike baseline run used by the analysis phase.
* ``Makefile`` — generic build rules wired to ``$(BENCHMARK)`` and
  ``$(SOURCES)``.
* ``benchmark.yaml`` — descriptor consumed by ``arvis.config`` to register
  the benchmark with the pipeline at next import.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

from arvis.cli import print_error, print_info, print_success

_TEMPLATE_NAME = "minimal"
_REQUIRED_FILES = (
    "crt0.S",
    "crt0_spike.S",
    "link.ld",
    "link_spike.ld",
    "Makefile",
)
_NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")

_STUB_MAIN_C = """\
/* {name} benchmark — generated by `arvis add-benchmark {name}`.
 *
 * Replace the body of main() with the workload you want ARVIS to specialise.
 * Return 0 for success and a non-zero value for failure; the CV32E40P
 * testbench uses this return value to verify functional correctness against
 * the Spike baseline.
 */
#include <stdint.h>

int main(void)
{{
    /* TODO: Add your workload here. */
    return 0;
}}
"""

_BENCHMARK_YAML = """\
# ARVIS benchmark descriptor for `{name}`.
name: {name}
elf: {name}_spike.elf
verilator_elf: {name}.elf
hex: {name}.hex
"""


def add_benchmark(name: str, *, benchmarks_root: Path | None = None) -> int:
    """Create a new benchmark directory.

    Returns 0 on success, non-zero on failure.
    """
    if not _NAME_RE.match(name):
        print_error(
            f"Invalid benchmark name: {name!r}. Use letters, digits, underscores or hyphens; must start with a letter."
        )
        return 2

    if benchmarks_root is None:
        # Use the project-root resolution from arvis.config so that this
        # subcommand works the same when invoked from inside a clone, with
        # ARVIS_PROJECT_ROOT set, or via `uv tool install`.
        from arvis.config import BENCHMARK_ROOT, _no_project_root_message

        if BENCHMARK_ROOT is None:
            print_error(_no_project_root_message())
            return 6
        benchmarks_root = BENCHMARK_ROOT

    template_dir = benchmarks_root / _TEMPLATE_NAME
    target_dir = benchmarks_root / name

    if not template_dir.is_dir():
        print_error(
            f"Template benchmark `{_TEMPLATE_NAME}` not found at {template_dir}. "
            "Cannot scaffold a new benchmark without it."
        )
        return 3

    if target_dir.exists():
        print_error(f"Benchmark already exists: {target_dir}")
        return 4

    missing = [f for f in _REQUIRED_FILES if not (template_dir / f).is_file()]
    if missing:
        print_error(f"Template `{_TEMPLATE_NAME}` is incomplete; missing: {', '.join(missing)}")
        return 5

    target_dir.mkdir(parents=True)

    # Copy template support files.
    for fname in _REQUIRED_FILES:
        shutil.copy2(template_dir / fname, target_dir / fname)

    # Write a fresh main.c stub instead of copying the template's content.
    (target_dir / "main.c").write_text(_STUB_MAIN_C.format(name=name), encoding="utf-8")

    # Write the YAML descriptor so the benchmark auto-registers next run.
    (target_dir / "benchmark.yaml").write_text(_BENCHMARK_YAML.format(name=name), encoding="utf-8")

    rel = target_dir.relative_to(benchmarks_root.parent.parent)
    print_success(f"Created benchmark `{name}` at {rel}")
    print_info("Next steps:")
    print_info(f"  1. Edit {rel}/main.c with your workload code.")
    print_info(f"  2. Run `uv run arvis run --benchmark {name}` to specialise it.")
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) != 1:
        print_error("Usage: arvis add-benchmark <name>")
        return 2
    return add_benchmark(argv[0])


if __name__ == "__main__":
    sys.exit(main())
